"use strict";
// 绿色包启动器生成器：Windows(launch.ps1) / macOS(launch.sh, start.command)
// 端口语义：desired = data/port.txt（期望端口）；running = data/runtime-port.txt（上次实际运行端口）
// desired != running 且 running 仍在监听 → 结束旧实例并按 desired 重启。

function makeLaunchPs1({ port, opencodeDir = "" }) {
  const ocLines = opencodeDir
    ? [
        "$ocDir = Join-Path $root '" + opencodeDir + "'",
        "if (Test-Path (Join-Path $ocDir 'opencode.exe')) { $env:PATH = $ocDir + ';' + $env:PATH }",
      ]
    : [];
  return [
    "param([switch]$NoBrowser, [switch]$NoShortcut, [switch]$Plan, [switch]$NoPrompt, [string]$Open = '', [string]$Assoc = '')",
    "$ErrorActionPreference = 'SilentlyContinue'",
    "$scriptDir = $PSScriptRoot",
    "if (-not $scriptDir) { $scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path }",
    "$root = Split-Path -Parent $scriptDir",
    "function Get-VoidVersion([string]$file) {",
    "  if (-not $file -or -not (Test-Path $file)) { return '' }",
    "  try { return ((Get-Content -Raw $file).Trim()) } catch { return '' }",
    "}",
    "function Compare-VoidVersion([string]$a, [string]$b) {",
    "  $ma = [regex]::Match([string]$a, '\\d+')",
    "  $mb = [regex]::Match([string]$b, '\\d+')",
    "  if ($ma.Success -and $mb.Success) {",
    "    $na = [long]$ma.Value; $nb = [long]$mb.Value",
    "    if ($na -gt $nb) { return 1 }",
    "    if ($na -lt $nb) { return -1 }",
    "    return 0",
    "  }",
    "  return [string]::Compare([string]$a, [string]$b, [System.StringComparison]::OrdinalIgnoreCase)",
    "}",
    "function Set-VoidAssoc([string]$action) {",
    "  $cu = [Microsoft.Win32.Registry]::CurrentUser",
    "  $all = @('.pdf', '.txt', '.md', '.markdown', '.yaml', '.yml', '.js', '.mjs', '.cjs', '.json', '.http', '.rest', '.curl')",
    "  $sel = @()",
    "  if ($action -ne 'remove') {",
    "    $sel = $all",
    "    try { if ($assocPref -and (Test-Path $assocPref)) { $p = Get-Content -Raw $assocPref | ConvertFrom-Json; if ($p.selected) { $sel = @($p.selected) } } } catch { }",
    "  }",
    "  $prog = $cu.CreateSubKey('Software\\Classes\\Void')",
    "  $prog.SetValue('', 'Void')",
    "  $cmd = $prog.CreateSubKey('shell\\open\\command')",
    "  $cmd.SetValue('', ('\"' + (Join-Path $root 'start.bat') + '\" \"%1\"'))",
    "  $cmd.Close()",
    "  $icon = $prog.CreateSubKey('DefaultIcon')",
    "  $icon.SetValue('', (Join-Path $scriptDir 'icon.ico'))",
    "  $icon.Close()",
    "  $prog.Close()",
    "  foreach ($e in $all) {",
    "    if ($sel -contains $e) {",
    "      try {",
    "        $k = $cu.CreateSubKey(\"Software\\Classes\\$e\")",
    "        $k.SetValue('', 'Void')",
    "        $k.Close()",
    "        $ow = $cu.CreateSubKey(\"Software\\Classes\\$e\\OpenWithProgids\")",
    "        $ow.SetValue('Void', (New-Object byte[] 0), [Microsoft.Win32.RegistryValueKind]::None)",
    "        $ow.Close()",
    "        $cu.DeleteSubKeyTree(\"Software\\Microsoft\\Windows\\CurrentVersion\\Explorer\\FileExts\\$e\\UserChoice\", $false)",
    "        $cu.DeleteSubKeyTree(\"Software\\Microsoft\\Windows\\CurrentVersion\\Explorer\\FileExts\\$e\\UserChoiceLatest\", $false)",
    "      } catch { }",
    "    } else {",
    "      try { $ow = $cu.OpenSubKey(\"Software\\Classes\\$e\\OpenWithProgids\", $true); if ($ow) { $ow.DeleteValue('Void', $false); $ow.Close() } } catch { }",
    "      try { $k = $cu.OpenSubKey(\"Software\\Classes\\$e\", $true); if ($k) { if ([string]$k.GetValue('') -eq 'Void') { $k.DeleteValue('', $false) }; $k.Close() } } catch { }",
    "    }",
    "  }",
    "  try {",
    "    $sig = '[DllImport(\"shell32.dll\")] public static extern void SHChangeNotify(int a, uint b, IntPtr c, IntPtr d);'",
    "    if (-not ('VoidApp.ShellNotify' -as [type])) { Add-Type -MemberDefinition $sig -Name ShellNotify -Namespace VoidApp }",
    "    [VoidApp.ShellNotify]::SHChangeNotify(0x08000000, 0, [IntPtr]::Zero, [IntPtr]::Zero)",
    "  } catch { }",
    "}",
    ...ocLines,
    "$fallback = " + port,
    "$desired = $fallback",
    "$df = Join-Path $root 'data\\port.txt'",
    "if (Test-Path $df) { $t = (Get-Content -Raw $df).Trim(); if ($t -match '^\\d+$') { $desired = [int]$t } }",
    "$running = $desired",
    "$rf = Join-Path $root 'data\\runtime-port.txt'",
    "if (Test-Path $rf) { $t = (Get-Content -Raw $rf).Trim(); if ($t -match '^\\d+$') { $running = [int]$t } }",
    "$dh = if ($env:DEVFLOW_DATA_HOME) { $env:DEVFLOW_DATA_HOME } else { Join-Path $env:USERPROFILE '.local\\share\\void' }",
    "$assocPref = Join-Path (Join-Path $dh ('ports\\' + $desired)) 'file-assoc.json'",
    "function Test-Port([int]$p) {",
    "  try {",
    "    $c = New-Object System.Net.Sockets.TcpClient",
    "    $iar = $c.BeginConnect('127.0.0.1', $p, $null, $null)",
    "    if (-not $iar.AsyncWaitHandle.WaitOne(300)) { $c.Close(); return $false }",
    "    $c.EndConnect($iar); $c.Close(); return $true",
    "  } catch { return $false }",
    "}",
    "$alive = Test-Port $running",
    "if ($alive -and ($desired -ne $running)) { $action = 'restart' }",
    "elseif ($alive) { $action = 'open' }",
    "else { $action = 'start' }",
    "if ($Plan) {",
    "  Write-Output ('PLAN desired={0} running={1} alive={2} action={3}' -f $desired, $running, [int]$alive, $action)",
    "  exit 0",
    "}",
    "if ($Assoc) { Set-VoidAssoc $Assoc; exit 0 }",
    "# 桌面快捷方式：只在当前版本不低于已指向版本时更新，避免旧包抢走新包的入口",
    "if (-not $NoShortcut) {",
    "  try {",
    "    $desktop = [Environment]::GetFolderPath('Desktop')",
    "    if ($desktop -and (Test-Path $desktop)) {",
    "      $lnkPath = Join-Path $desktop 'Void.lnk'",
    "      $curVer = Get-VoidVersion (Join-Path $root 'version.txt')",
    "      $update = $true",
    "      $ws = New-Object -ComObject WScript.Shell",
    "      $lnk = $ws.CreateShortcut($lnkPath)",
    "      if (Test-Path $lnkPath) {",
    "        $target = $lnk.TargetPath",
    "        $targetRoot = if ($target) { Split-Path -Parent $target } else { '' }",
    "        if (-not $targetRoot) { $targetRoot = [string]$lnk.WorkingDirectory }",
    "        if ($targetRoot) {",
    "          $oldVer = Get-VoidVersion (Join-Path $targetRoot 'version.txt')",
    "          if ($curVer -and $oldVer -and ((Compare-VoidVersion $oldVer $curVer) -gt 0)) { $update = $false }",
    "        }",
    "      }",
    "      if ($update) {",
    "        $lnk.TargetPath = Join-Path $root 'start.bat'",
    "        $lnk.WorkingDirectory = $root",
    "        $lnk.IconLocation = (Join-Path $scriptDir 'icon.ico')",
    "        $lnk.Description = 'Void'",
    "        $lnk.Save()",
    "      }",
    "    }",
    "  } catch { }",
    "}",
    "# 每次启动（含已在运行）：设置里启用了就把默认打开方式静默校正为 Void",
    "try {",
    "  if (Test-Path $assocPref) {",
    "    $pref = Get-Content -Raw $assocPref | ConvertFrom-Json",
    "    if ($pref.enabled) { Set-VoidAssoc 'apply' }",
    "  }",
    "} catch { }",
    "$openPort = $desired",
    "if ($action -eq 'restart') {",
    "  $killed = $false",
    "  try {",
    "    $conns = Get-NetTCPConnection -State Listen -LocalPort $running -ErrorAction SilentlyContinue",
    "    foreach ($c in @($conns)) {",
    "      $p = Get-CimInstance Win32_Process -Filter ('ProcessId=' + $c.OwningProcess) -ErrorAction SilentlyContinue",
    "      if (-not $p) { continue }",
    "      $exe = [string]$p.ExecutablePath",
    "      $cmd = [string]$p.CommandLine",
    "      $isOurs = ($exe -ieq (Join-Path $root 'runtime\\node.exe')) -or ($cmd -match 'server\\\\index\\.js')",
    "      if ($isOurs) { Stop-Process -Id $p.ProcessId -Force -ErrorAction SilentlyContinue; $killed = $true }",
    "      else { Write-Output ('WARN 端口 {0} 被非本应用进程占用（PID {1}），未结束' -f $running, $p.ProcessId) }",
    "    }",
    "  } catch { }",
    "  if ($killed) { Start-Sleep -Milliseconds 500 }",
    "}",
    "if ($action -eq 'open') {",
    "  # 已在运行：只打开浏览器后立即退出，跳过启动/快捷方式/关联提示",
    "  if (-not $NoBrowser) {",
    "    if ($Open) { Start-Process ('http://127.0.0.1:{0}/?open={1}' -f $running, [uri]::EscapeDataString($Open)) }",
    "    else { Start-Process ('http://127.0.0.1:{0}' -f $running) }",
    "  }",
    "  exit 0",
    "}",
    "# 启动失败时把 node 的输出留下来，并弹窗提示原因，避免「双击没反应」",
    "$started = $true",
    "$logDir = Join-Path $root 'logs'",
    "$logOut = Join-Path $logDir 'server.log'",
    "$logErr = Join-Path $logDir 'server.err.log'",
    "if ($action -ne 'open') {",
    "  try { New-Item -ItemType Directory -Force -Path $logDir | Out-Null } catch { }",
    "  Start-Process -FilePath (Join-Path $root 'runtime\\node.exe') -ArgumentList 'server\\index.js' -WorkingDirectory $root -WindowStyle Minimized -RedirectStandardOutput $logOut -RedirectStandardError $logErr",
    "  $deadline = (Get-Date).AddSeconds(20)",
    "  while ((Get-Date) -lt $deadline -and -not (Test-Port $openPort)) { Start-Sleep -Milliseconds 400 }",
    "  $started = Test-Port $openPort",
    "}",
    "if (-not $started) {",
    "  $tail = ''",
    "  foreach ($f in @($logErr, $logOut)) {",
    "    if ($tail) { break }",
    "    try {",
    "      if (Test-Path -LiteralPath $f) {",
    "        $t = (Get-Content -LiteralPath $f -Tail 15 -ErrorAction SilentlyContinue) -join [Environment]::NewLine",
    "        if ($t) { $tail = $t }",
    "      }",
    "    } catch { }",
    "  }",
    "  if (-not $tail) { $tail = '(no output captured)' }",
    "  $msg = @(('Void failed to start on port ' + $openPort + '.'), '', $tail, '', ('Logs: ' + $logDir)) -join [Environment]::NewLine",
    "  if (-not $NoPrompt) { try { $wshErr = New-Object -ComObject WScript.Shell; [void]$wshErr.Popup($msg, 0, 'Void', 16 + 4096) } catch { } }",
    "  Write-Output $msg",
    "  exit 1",
    "}",
    "",
    "if (-not $NoBrowser) {",
    "  if ($Open) { Start-Process ('http://127.0.0.1:{0}/?open={1}' -f $openPort, [uri]::EscapeDataString($Open)) }",
    "  else { Start-Process ('http://127.0.0.1:{0}' -f $openPort) }",
    "}",
    "",
  ].join("\r\n");
}

function makeLaunchSh({ port }) {
  return [
    "#!/bin/bash",
    "# Void launcher (macOS). Run start.command, or: bash script/launch.sh",
    "set -u",
    'DIR="$(cd "$(dirname "$0")/.." && pwd)"',
    'cd "$DIR" || exit 1',
    "",
    "# desired = data/port.txt（期望端口）；running = data/runtime-port.txt（上次实际运行端口）",
    "FALLBACK=" + port,
    'DESIRED="$FALLBACK"',
    'if [ -f "data/port.txt" ]; then',
    '  T="$(tr -cd \'0-9\' < "data/port.txt")"; if [ -n "$T" ]; then DESIRED="$T"; fi',
    "fi",
    'RUNNING="$DESIRED"',
    'if [ -f "data/runtime-port.txt" ]; then',
    '  T="$(tr -cd \'0-9\' < "data/runtime-port.txt")"; if [ -n "$T" ]; then RUNNING="$T"; fi',
    "fi",
    'PORT="$DESIRED"',
    'URL="http://127.0.0.1:${PORT}"',
    "",
    "# 存活探测",
    'if /usr/bin/nc -z 127.0.0.1 "$RUNNING" >/dev/null 2>&1; then ALIVE=1; else ALIVE=0; fi',
    'if [ "$ALIVE" = "1" ] && [ "$RUNNING" != "$DESIRED" ]; then ACTION="restart";',
    'elif [ "$ALIVE" = "1" ]; then ACTION="open"; PORT="$RUNNING"; URL="http://127.0.0.1:${RUNNING}";',
    'else ACTION="start"; fi',
    'if [ "${1:-}" = "--plan" ]; then',
    '  echo "PLAN desired=${DESIRED} running=${RUNNING} alive=${ALIVE} action=${ACTION}"',
    "  exit 0",
    "fi",
    "",
    "# 已在期望端口运行：只打开浏览器",
    'if [ "$ACTION" = "open" ]; then',
    '  open "$URL"',
    "  exit 0",
    "fi",
    "",
    "# 期望端口与运行端口不一致：mac 为前台运行，提示用户关窗后重开",
    'if [ "$ACTION" = "restart" ]; then',
    '  echo "已在 :${RUNNING} 运行；关闭该终端窗口后重新打开 start.command 即会切到 :${DESIRED}"',
    '  open "http://127.0.0.1:${RUNNING}"',
    "  exit 0",
    "fi",
    "",
    "# 未运行：稍后自动开浏览器，然后前台启动服务（关闭本终端窗口或 Ctrl-C 即停止）",
    '( sleep 1.5; open "$URL" ) >/dev/null 2>&1 &',
    'exec "$DIR/runtime/node" "server/index.js"',
    "",
  ].join("\n");
}

function makeStartCommand() {
  return [
    "#!/bin/bash",
    'DIR="$(cd "$(dirname "$0")" && pwd)"',
    'exec "$DIR/script/launch.sh" "$@"',
    "",
  ].join("\n");
}

module.exports = { makeLaunchPs1, makeLaunchSh, makeStartCommand };
